-- เดิมบิลตรึงตัวเลข ณ วันออกทุกใบ การแก้เลขมิเตอร์ที่พิมพ์ผิดจึงต้องยกเลิกใบเดิม
-- แล้วออกใหม่ ซึ่งกินเลขที่บิล (invoices_no_per_dorm) และผู้เช่าเห็นการ์ดที่ยอด
-- ผิดในแชทไปแล้ว · ตั้งแต่ไฟล์นี้ บิลที่ยัง `unpaid` ถูกคำนวณใหม่ในใบเดิมได้
-- โดยคงเลขที่บิลและ revision ไว้ ส่วนใบที่ส่งสลิป/จ่าย/ยกเลิกแล้วยังตรึงตลอดไป
--
-- สองคอลัมน์นี้ไม่ได้บังคับให้แอปทำงาน — InvoiceService อ่านบิลด้วย `*` จึงมองไม่
-- เห็นคอลัมน์ที่ยังไม่มีแล้วอ่านเป็น NULL ตามปกติ แต่การ **เขียน** ยอดใหม่จะตกด้วย
-- 42703 จนกว่าจะรันไฟล์นี้

BEGIN;

-- ร่องรอยว่าใบนี้เคยถูกคำนวณใหม่ · หน้าจอใช้ขึ้นป้าย "ปรับยอดแล้ว" ให้ทั้งสองฝ่าย
-- เห็นว่ายอดที่ถืออยู่ไม่ใช่ยอดตั้งต้นอีกแล้ว
ALTER TABLE invoices ADD COLUMN IF NOT EXISTS recalculated_at TIMESTAMPTZ;

-- ยอดก่อนการคำนวณครั้งล่าสุด · เก็บไว้เพื่อให้การ์ดบิลบอกได้ว่า "จากเท่าไร"
-- ไม่ใช่แค่ "เปลี่ยนแล้ว" ซึ่งไม่พอให้ผู้เช่าตรวจสอบอะไรได้เลย
ALTER TABLE invoices ADD COLUMN IF NOT EXISTS previous_total NUMERIC;

COMMENT ON COLUMN invoices.recalculated_at IS
  'เวลาที่ยอดถูกคำนวณใหม่ตามข้อมูลล่าสุดของงวด · NULL = ยังเป็นยอดตั้งแต่วันออกบิล';
COMMENT ON COLUMN invoices.previous_total IS
  'ยอดรวมก่อนการคำนวณครั้งล่าสุด · คู่กับ recalculated_at';

COMMIT;
