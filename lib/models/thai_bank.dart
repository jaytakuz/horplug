/// ธนาคารในประเทศไทยที่รับโอนเงินได้
///
/// เก็บลงฐานข้อมูลเป็น **ชื่อเต็มภาษาไทย** ไม่ใช่รหัส เพราะคอลัมน์ `bank_name`
/// มีข้อมูลที่เจ้าของหอพิมพ์เองอยู่ก่อนแล้ว การเปลี่ยนไปเก็บรหัสต้องมี migration
/// ที่แปลงข้อความอิสระให้เป็นรหัส ซึ่งเดาผิดได้ทุกแถวที่สะกดไม่ตรง · ชื่อธนาคาร
/// ไทยแทบไม่เปลี่ยน (ทหารไทย+ธนชาต เป็น ttb คือครั้งเดียวในรอบยี่สิบปี) และถ้า
/// เปลี่ยนจริงก็แก้ที่นี่แล้ว UPDATE แถวเดียว
///
/// เรียงตามที่คนไทยคุ้นเคย — ธนาคารพาณิชย์ใหญ่ก่อน แล้วตามด้วยธนาคารรัฐ
enum ThaiBank {
  bbl('ธนาคารกรุงเทพ'),
  kbank('ธนาคารกสิกรไทย'),
  ktb('ธนาคารกรุงไทย'),
  scb('ธนาคารไทยพาณิชย์'),
  bay('ธนาคารกรุงศรีอยุธยา'),
  ttb('ธนาคารทหารไทยธนชาต'),
  kkp('ธนาคารเกียรตินาคินภัทร'),
  cimbt('ธนาคารซีไอเอ็มบี ไทย'),
  tisco('ธนาคารทิสโก้'),
  uobt('ธนาคารยูโอบี'),
  lhb('ธนาคารแลนด์ แอนด์ เฮ้าส์'),
  tcd('ธนาคารไทยเครดิต'),
  icbct('ธนาคารไอซีบีซี (ไทย)'),
  gsb('ธนาคารออมสิน'),
  ghb('ธนาคารอาคารสงเคราะห์'),
  baac('ธนาคารเพื่อการเกษตรและสหกรณ์การเกษตร'),
  ibank('ธนาคารอิสลามแห่งประเทศไทย');

  const ThaiBank(this.displayName);

  /// ชื่อที่แสดงและที่เก็บลงฐานข้อมูล
  final String displayName;

  /// หาธนาคารจากชื่อที่เก็บไว้ · null เมื่อไม่ตรงกับรายการใด
  ///
  /// คืน null แทนการเดา เพราะหอที่เคยพิมพ์ชื่อเองอาจใส่ "กสิกร" หรือ
  /// "KBank" ไว้ ซึ่งหน้าจอต้องแสดงค่าเดิมนั้นต่อไปได้ ไม่ใช่เปลี่ยนธนาคาร
  /// ให้เขาเงียบๆ ด้วยการเดาที่ใกล้เคียงที่สุด
  static ThaiBank? fromName(String? name) {
    final trimmed = name?.trim();
    if (trimmed == null || trimmed.isEmpty) return null;

    for (final bank in ThaiBank.values) {
      if (bank.displayName == trimmed) return bank;
    }
    return null;
  }
}
